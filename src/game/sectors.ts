/** Reality odomknuté na začiatku komory i (kryštály zo skorších komôr). */
export function unlockedAt(i: number): number[] {
  const out = new Set([0]);
  for (const s of SECTORS.slice(0, i)) {
    for (const [ch, spec] of Object.entries(s.legend ?? {})) {
      if (spec.k === 'crystal' && s.layers.some((rows) => rows.some((row) => row.includes(ch))))
        out.add(spec.reality);
    }
  }
  return [...out].sort();
}
